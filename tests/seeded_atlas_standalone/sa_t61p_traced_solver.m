function rows = sa_t61p_traced_solver(E)
%SA_T61P_TRACED_SOLVER  The
%   portable check of the traced bvp4c copy. It generates into scratch only
%   and never moves, rewrites or deletes the installed copy. About 36 tiny
%   bvp4c calls (three self-checks).
%   - a fresh generation from this MATLAB's toolbox: the copy differs from
%     the toolbox bvp4c.m only at the function line and the two inserted
%     sa_mesh_trace lines, each right after its anchor; it equals the
%     installed copy (when present) byte for byte; on the reference toolbox
%     it has the reference SHA-256;
%   - the closure: the copied helpers are byte copies of the toolbox's and
%     no other <toolbox>/private name occurs in the copy or the helpers; on
%     the reference toolbox exactly the five reference helpers;
%   - the record names the anchors (exact or tolerant) and lines; the
%     self-check passed; the three message identifiers resolve;
%   - refusals on fake toolboxes (scratch copies): a missing function-line
%     anchor E_ANCHOR, a .p sibling E_TOOLBOX, a removed helper E_CLOSURE;
%   - verification refusals: a missing or edited generated copy or helper
%     E_TRACED; a changed toolbox file after generation E_TOOLBOX;
%   - the run-level refusal at zero calls on the stub model: a module whose
%     version carries the solver component of a scratch copy with the traced
%     file removed (or edited) refuses the run with E_TRACED and writes no
%     run-folder file; with the intact copy the run completes.
T = 'T61p traced solver (portable)';
rows = struct('test', {}, 'assertion', {}, 'pass', {}, 'detail', {});
P = sa_bvp4c_setup('pins');
tb = sa_bvp4c_setup('locate');
sd = fullfile(E.pkg, 'solver');
d = sa_m3_testdir(E, 't61p');
ref = strcmp(sha(fullfile(tb, 'bvp4c.m')), P.bvp4c);
inst = fullfile(sd, 'sa_bvp4c_traced.m');
inst0 = bytes_or_empty(inst);                          % the installed copy is never touched
% ---- generation, text diff ------------------------------------------------------------------------
g = fullfile(d, 'gen');
R = sa_bvp4c_setup('generate', g);
Lt = lines_of(fullfile(tb, 'bvp4c.m'));
Lg = lines_of(fullfile(g, 'sa_bvp4c_traced.m'));
ins = find(contains(Lg, 'sa_bvp4c_setup: inserted (mesh trace)'));
rest = Lg; rest(ins) = [];
i1 = num(R.anchor_function); i2 = num(R.anchor_initial); i3 = num(R.anchor_proposal);
ok = numel(ins) == 2 && numel(Lg) == numel(Lt) + 2 && isequal(find(~cellfun(@isequal, rest, Lt)), i1) && ...
    isequal(ins, [i2 + 1, i3 + 2]) && strcmp(Lg{i2}, Lt{i2}) && strcmp(Lg{i3 + 1}, Lt{i3}) && ...
    startsWith(Lg{i1}, sprintf('function sol = sa_bvp4c_traced(ode, bc, solinit, options, varargin) %% GENERATED by sa_bvp4c_setup from %s bvp4c.m', R.release));
same = ~isfile(inst) || isequal(bytes(inst), bytes(fullfile(g, 'sa_bvp4c_traced.m')));
okref = ~ref || strcmp(sha(fullfile(g, 'sa_bvp4c_traced.m')), P.traced);
rows = sa_check(rows, T, ['a fresh generation (scratch) differs from the toolbox bvp4c.m only at the function line and the ' ...
    'two inserted lines, each right after its anchor; equals the installed copy byte for byte; reference SHA-256 on the ' ...
    'reference toolbox'], ok && same && okref, sprintf(['inserted at %s of %d lines (toolbox %d); anchors %s / %s / %s; ' ...
    'installed equal %d; reference toolbox %d, sha %s'], mat2str(ins), numel(Lg), numel(Lt), R.anchor_function, ...
    R.anchor_initial, R.anchor_proposal, same, ref, sha(fullfile(g, 'sa_bvp4c_traced.m'))));
% ---- closure ---------------------------------------------------------------------------------------
okh = ~isempty(R.helpers); det = {};
for k = 1:numel(R.helpers)
    a = sha(fullfile(tb, 'private', R.helpers{k})); b = sha(fullfile(g, 'private', R.helpers{k}));
    okh = okh && strcmp(a, b);
    det{end+1} = sprintf('%s %s', R.helpers{k}, a(1:12)); %#ok<AGROW>
end
pl = dir(fullfile(g, 'private', '*')); pl = pl(~[pl.isdir]);
pv = dir(fullfile(tb, 'private', '*.m'));
pn = setdiff(strrep({pv.name}, '.m', ''), strrep(R.helpers, '.m', ''));
files = [{fullfile(g, 'sa_bvp4c_traced.m')}, cellfun(@(n) fullfile(g, 'private', n), R.helpers, 'UniformOutput', false)];
hits = {};
for k = 1:numel(files)
    c = char(bytes(files{k}));
    for q = 1:numel(pn)
        if ~isempty(regexp(c, ['\<' pn{q} '\>'], 'once')), hits{end+1} = sprintf('%s in %s', pn{q}, files{k}); end %#ok<AGROW>
    end
end
okr = ~ref || isequal(sort(R.helpers), sort({P.helpers.name}));
rows = sa_check(rows, T, sprintf(['the closure: %d helpers, byte copies of the toolbox''s, nothing else in private/; none ' ...
    'of the other %d toolbox private names occurs in the copy or the helpers; the five reference helpers on the ' ...
    'reference toolbox'], numel(R.helpers), numel(pn)), okh && numel(pl) == numel(R.helpers) && isempty(hits) && okr, ...
    strjoin([det, hits], '; '));
% ---- record: anchors, self-check, identifiers ---------------------------------------------------------
ids = {'MATLAB:bvp4c:RelTolNotMet', 'MATLAB:bvp4c:IllCondJac', 'MATLAB:bvp4c:SingJac'};
okid = all(cellfun(@resolves, ids));
okc = startsWith(R.selfcheck, 'pass(') && contains(R.selfcheck_cases, 'h=pass') && ...
    all(cellfun(@(c) contains(R.selfcheck_cases, [c '=pass']), {'a', 'b', 'c', 'd', 'g'})) && ...
    strcmp(R.selfcheck_threads, '1') && strcmp(R.selfcheck_control, 'deterministic') && ...
    ~isempty(regexp(R.anchor_function, '^(exact|tolerant) line \d+$', 'once')) && ...
    ~isempty(regexp(R.anchor_initial, '^(exact|tolerant) line \d+$', 'once')) && ...
    ~isempty(regexp(R.anchor_proposal, '^(exact|tolerant) line \d+$', 'once')) && i2 < i3 && ...
    i3 <= str2double(R.main_body_end) && (~ref || (strcmp(R.toolbox_label, 'reference') && ...
    strcmp(R.deval_mode, 'replica') && strcmp(R.anchor_initial, 'exact line 146') && ...
    strcmp(R.anchor_proposal, 'exact line 263')));
rows = sa_check(rows, T, ['the record: anchors (path and line, both in the main body, in order), the self-check passed ' ...
    '(cases a b c d g h; single thread; deterministic control), reference/replica on the reference toolbox; ' ...
    'RelTolNotMet, IllCondJac and SingJac resolve in the message catalog'], okid && okc, ...
    sprintf('%s | %s | %s | %s %s', R.selfcheck, R.selfcheck_cases, R.toolbox_label, R.deval_mode, R.anchor_proposal));
% ---- refusals on fake toolboxes --------------------------------------------------------------------------
fk = fake(tb, fullfile(d, 'fake_anchor'), R.helpers);
txt = char(bytes(fullfile(fk, 'bvp4c.m')));
L = strsplit(txt, newline, 'CollapseDelimiters', false);
L{i1} = strrep(L{i1}, 'function sol = bvp4c(', 'function out = bvp4c(');
put(fullfile(fk, 'bvp4c.m'), strjoin(L, newline));
ea = err(@() sa_bvp4c_setup('generate', fullfile(d, 'gen_anchor'), fk));
fp = fake(tb, fullfile(d, 'fake_p'), R.helpers);
put(fullfile(fp, 'bvp4c.p'), 'not a real p-file');
ep = err(@() sa_bvp4c_setup('generate', fullfile(d, 'gen_p'), fp));
fc = fake(tb, fullfile(d, 'fake_closure'), R.helpers);
delete(fullfile(fc, 'private', R.helpers{end}));
ec = err(@() sa_bvp4c_setup('generate', fullfile(d, 'gen_closure'), fc));
nf = [numel(dir(fullfile(d, 'gen_anchor', '*.m'))), numel(dir(fullfile(d, 'gen_p', '*.m'))), ...
    numel(dir(fullfile(d, 'gen_closure', '*.m')))];
rows = sa_check(rows, T, ['refusals on fake toolboxes (scratch copies): a changed function line is E_ANCHOR, a .p sibling ' ...
    'of bvp4c.m E_TOOLBOX, a removed helper E_CLOSURE; nothing is written'], strcmp(ea, 'SA:SOLVER:E_ANCHOR') && ...
    strcmp(ep, 'SA:SOLVER:E_TOOLBOX') && strcmp(ec, 'SA:SOLVER:E_CLOSURE') && ~any(nf), ...
    sprintf('%s / %s / %s; files %s', ea, ep, ec, mat2str(nf)));
% ---- verification refusals ----------------------------------------------------------------------------------
fv = fake(tb, fullfile(d, 'fake_verify'), R.helpers);
v = fullfile(d, 'gen_verify');
sa_bvp4c_setup('generate', v, fv);
e0 = err(@() sa_bvp4c_setup('verify', v, fv));
movefile(fullfile(v, 'sa_bvp4c_traced.m'), fullfile(d, 'traced_aside.m'));
e1 = err(@() sa_bvp4c_setup('verify', v, fv));
movefile(fullfile(d, 'traced_aside.m'), fullfile(v, 'sa_bvp4c_traced.m'));
e1b = err(@() sa_bvp4c_setup('verify', v, fv));
copyfile(fullfile(v, 'sa_bvp4c_traced.m'), fullfile(d, 'traced_keep.m'));
fid = fopen(fullfile(v, 'sa_bvp4c_traced.m'), 'a'); fprintf(fid, '%%x\n'); fclose(fid);
e2 = err(@() sa_bvp4c_setup('verify', v, fv));
copyfile(fullfile(d, 'traced_keep.m'), fullfile(v, 'sa_bvp4c_traced.m'), 'f');
copyfile(fullfile(v, 'private', R.helpers{1}), fullfile(d, 'helper_keep.m'));
delete(fullfile(v, 'private', R.helpers{1}));
e3 = err(@() sa_bvp4c_setup('verify', v, fv));
copyfile(fullfile(d, 'helper_keep.m'), fullfile(v, 'private', R.helpers{1}));
fid = fopen(fullfile(fv, 'deval.m'), 'a'); fprintf(fid, '%%x\n'); fclose(fid);
e4 = err(@() sa_bvp4c_setup('verify', v, fv));
rows = sa_check(rows, T, ['verification: an intact copy verifies; a missing or edited generated copy, or a missing helper, ' ...
    'is E_TRACED; a toolbox file changed after generation is E_TOOLBOX'], isempty(e0) && isempty(e1b) && ...
    strcmp(e1, 'SA:SOLVER:E_TRACED') && strcmp(e2, 'SA:SOLVER:E_TRACED') && strcmp(e3, 'SA:SOLVER:E_TRACED') && ...
    strcmp(e4, 'SA:SOLVER:E_TOOLBOX'), sprintf('"%s" %s "%s" %s %s %s', e0, e1, e1b, e2, e3, e4));
% ---- the run-level refusal on the stub ---------------------------------------------------------------------------
addpath(E.stub);
fac = fullfile(d, 'factory');
mkdir(fac);
put(fullfile(fac, 'sa_model_stub_t61p.m'), strjoin({
    'function M = sa_model_stub_t61p()'
    '% T61p test fixture: the stub model carrying the solver component of a scratch traced copy'
    'M = sa_model_stub_two_pool();'
    'M.id = ''stub_t61p'';'
    'M.version = [''stub_t61p/1 (test fixture)'' sa_bvp4c_setup(''component'', getappdata(0, ''SA_T61P_MODEL''), getappdata(0, ''SA_T61P_SOLVER''), getappdata(0, ''SA_T61P_TB''))];'
    'end'}, newline));
addpath(fac);
rs = fullfile(d, 'gen_run');
sa_bvp4c_setup('generate', rs);
setappdata(0, 'SA_T61P_MODEL', fullfile(E.pkg, 'models', 'original_polarity'));
setappdata(0, 'SA_T61P_SOLVER', rs);
setappdata(0, 'SA_T61P_TB', tb);
c0 = onCleanup(@rm_apps);
st = struct('model', 'stub_t61p', 'budget', struct('max_calls', 3));
Rok = fullfile(d, 'run_ok');
[eok, rok] = err(@() sa_m3_run(Rok, [1 1], 'settings', st));
movefile(fullfile(rs, 'sa_bvp4c_traced.m'), fullfile(d, 'run_traced_aside.m'));
Rm = fullfile(d, 'run_missing');
em = err(@() sa_m3_run(Rm, [1 1], 'settings', st));
movefile(fullfile(d, 'run_traced_aside.m'), fullfile(rs, 'sa_bvp4c_traced.m'));
fid = fopen(fullfile(rs, 'sa_bvp4c_traced.m'), 'a'); fprintf(fid, '%% planted edit\n'); fclose(fid);
Re = fullfile(d, 'run_edited');
ee = err(@() sa_m3_run(Re, [1 1], 'settings', st));
nm = nfiles(Rm); ne = nfiles(Re);
rows = sa_check(rows, T, ['the run-level refusal at zero calls (stub model carrying the solver component of a scratch ' ...
    'copy): with the intact copy the run completes; with the traced file missing or edited the run is refused ' ...
    'E_TRACED and no run-folder file is written; the installed copy is never touched'], isempty(eok) && ...
    isstruct(rok) && strcmp(em, 'SA:SOLVER:E_TRACED') && strcmp(ee, 'SA:SOLVER:E_TRACED') && nm == 0 && ne == 0 && ...
    isequal(bytes_or_empty(inst), inst0), sprintf('ok "%s"; missing %s (%d files); edited %s (%d files)', ...
    eok, em, nm, ee, ne));
rmpath(fac); rmpath(E.stub);
end

% =========================================================================

function b = bytes_or_empty(f)
if isfile(f), b = bytes(f); else, b = []; end
end

function rm_apps()
for k = {'SA_T61P_MODEL', 'SA_T61P_SOLVER', 'SA_T61P_TB'}
    if isappdata(0, k{1}), rmappdata(0, k{1}); end
end
end

function n = nfiles(d)
n = 0;
if exist(d, 'dir') == 7
    L = dir(fullfile(d, '**', '*'));
    n = sum(~[L.isdir]);
end
end

function fk = fake(tb, fk, helpers)
% a writable scratch copy of the toolbox files the copy is made from
mkdir(fullfile(fk, 'private'));
copyfile(fullfile(tb, 'bvp4c.m'), fk); copyfile(fullfile(tb, 'deval.m'), fk);
for k = 1:numel(helpers), copyfile(fullfile(tb, 'private', helpers{k}), fullfile(fk, 'private')); end
fileattrib(fk, '+w', 'u', 's');
end

function n = num(s)
n = str2double(regexp(s, '\d+$', 'match', 'once'));
end

function tf = resolves(id)
tf = false;
for n = 0:6
    a = num2cell(ones(1, n));
    try
        tf = ~isempty(getString(message(id, a{:})));
        return
    catch ME
        if strcmp(ME.identifier, 'MATLAB:builtins:MessageNotFound'), return; end
    end
end
end

function [e, out] = err(fn)
e = ''; out = [];
try
    if nargout > 1, out = fn(); else, fn(); end
catch ME
    e = ME.identifier;
end
end

function put(f, txt)
fid = fopen(f, 'w'); fwrite(fid, uint8(txt), 'uint8'); fclose(fid);
end

function b = bytes(f)
fid = fopen(f, 'r'); b = fread(fid, Inf, '*uint8').'; fclose(fid);
end

function L = lines_of(f)
L = strsplit(char(bytes(f)), newline, 'CollapseDelimiters', false);
end

function h = sha(f)
md = java.security.MessageDigest.getInstance('SHA-256');
b = bytes(f);
if ~isempty(b), md.update(typecast(b(:), 'int8')); end
dd = typecast(md.digest(), 'uint8');
h = lower(reshape(dec2hex(dd, 2).', 1, []));
end
